export function renderLucideIcon(iconNode: IconNode, attrs: SVGProps = {}): string {
  const defaultAttrs: SVGProps = {
    width: 18,
    height: 18,
    strokeWidth: 2,
    class: "aq-icon",
    ...attrs,
  };
  return createElement(iconNode, defaultAttrs).outerHTML;
}

